/**
 * P2P Voice React Hooks
 *
 * Same public interface as the old mediasoup-era hooks (VoiceProvider,
 * useVoice, useVoiceConnection, useVoiceMute, useRemoteParticipants,
 * useRemoteParticipant, useAudioDevices, useVoiceEvent, useOnSpeaking,
 * useLocalSpeaking) so UI components work without changes.
 *
 * Differences under the hood:
 *  - No auth-token / socket.io gate: guest-first, initializes on mount.
 *  - Signaling runs over Convex (api.signals.push / api.signals.poll).
 *  - Peer discovery reads the Convex presence list (api.presence.listForRoom).
 */

'use client';

import {
    useState,
    useEffect,
    useCallback,
    useRef,
    useMemo,
    createContext,
    useContext,
    type ReactNode,
} from 'react';
import { useQuery, useMutation } from 'convex/react';
// @ts-expect-error - generated by `npx convex dev`
import { api } from '@/convex/_generated/api';
import { getDeviceId } from '@/lib/guest';
import {
    getVoiceService,
    initialVoiceState,
    type P2PVoiceService,
    type VoiceState,
    type VoiceConnectionState,
    type RemoteParticipant,
    type AudioDeviceOptions,
    type JoinRoomOptions,
} from './index';

// ============================================================================
// VOICE CONTEXT
// ============================================================================

interface VoiceContextValue {
    service: P2PVoiceService;
    state: VoiceState;
    isInitialized: boolean;
}

const VoiceContext = createContext<VoiceContextValue | null>(null);

interface VoiceProviderProps {
    children: ReactNode;
    debug?: boolean;
    /** Override for tests; defaults to the guest deviceId. */
    deviceId?: string;
}

/**
 * Voice Provider — initializes the P2P mesh service and wires Convex
 * signaling. No login required: identity is the guest deviceId.
 */
export function VoiceProvider({ children, debug = false, deviceId: deviceIdProp }: VoiceProviderProps) {
    const [isInitialized, setIsInitialized] = useState(false);
    const [initError, setInitError] = useState<Error | null>(null);
    const deviceId = useMemo(
        () => deviceIdProp ?? (typeof window === 'undefined' ? 'ssr' : getDeviceId()),
        [deviceIdProp]
    );
    const serviceRef = useRef<P2PVoiceService | null>(null);
    if (!serviceRef.current && typeof window !== 'undefined') {
        serviceRef.current = getVoiceService({ deviceId, debug });
    }
    const [state, setState] = useState<VoiceState>(() =>
        serviceRef.current ? serviceRef.current.getState() : initialVoiceState()
    );
    const mountedRef = useRef(true);

    const pushSignal = useMutation(api.signals.push);
    const pollSignals = useMutation(api.signals.poll);

    // Presence list drives peer discovery (only queried while in a room).
    const currentRoomId = state.currentRoomId;
    const participants = useQuery(
        api.presence.listForRoom,
        currentRoomId ? { roomId: currentRoomId as any } : 'skip'
    );

    // --- init ----------------------------------------------------------
    useEffect(() => {
        const service = serviceRef.current;
        if (!service) return;
        mountedRef.current = true;
        let cancelled = false;

        // Outbound signaling → Convex.
        service.setSignalOut((toDeviceId, type, payload) => {
            const roomId = service.getState().currentRoomId;
            if (!roomId) return;
            pushSignal({
                roomId: roomId as any,
                fromDeviceId: deviceId,
                toDeviceId,
                type,
                payload: JSON.stringify(payload),
            }).catch((err) => console.error('[voice] signal push failed', err));
        });

        service
            .initialize()
            .then(() => {
                if (!cancelled && mountedRef.current) {
                    setIsInitialized(true);
                    setInitError(null);
                }
            })
            .catch((err) => {
                console.error('[VoiceProvider] init failed', err);
                if (mountedRef.current) {
                    setInitError(err instanceof Error ? err : new Error(String(err)));
                }
            });

        const unsubscribe = service.on('state-changed', (newState) => {
            if (mountedRef.current) setState(newState);
        });

        return () => {
            cancelled = true;
            mountedRef.current = false;
            unsubscribe();
            // Leave the mesh on unmount (page navigation).
            void service.leaveRoom().catch(() => {});
        };
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [deviceId]);

    // --- inbound signaling poll ----------------------------------------
    useEffect(() => {
        const service = serviceRef.current;
        if (!service || !isInitialized || !currentRoomId) return;
        let cancelled = false;

        const tick = async () => {
            if (cancelled) return;
            try {
                const signals = (await pollSignals({
                    roomId: currentRoomId as any,
                    deviceId,
                })) as Array<{ fromDeviceId: string; type: 'offer' | 'answer' | 'ice' | 'track-meta'; payload: string }>;
                for (const s of signals) {
                    if (cancelled) return;
                    let payload: unknown = s.payload;
                    try {
                        payload = JSON.parse(s.payload);
                    } catch { /* raw */ }
                    await service.handleSignal(s.fromDeviceId, s.type, payload);
                }
            } catch (err) {
                console.error('[voice] signal poll failed', err);
            }
        };

        void tick();
        const timer = setInterval(tick, 1500);
        return () => {
            cancelled = true;
            clearInterval(timer);
        };
    }, [isInitialized, currentRoomId, deviceId, pollSignals]);

    // --- peer discovery from presence -----------------------------------
    // NOTE: isConnected is a dep on purpose — peers already in the room when
    // joinRoom() resolves need a sync pass after the mic is live.
    const isConnected = state.isConnected;
    useEffect(() => {
        const service = serviceRef.current;
        if (!service || !isInitialized || !currentRoomId || !participants) return;
        const ids = (participants as Array<{ deviceId: string }>).map((p) => p.deviceId);
        service.syncPeers(ids);
    }, [isInitialized, currentRoomId, isConnected, participants]);

    const value = useMemo(
        () => ({
            service: serviceRef.current as P2PVoiceService,
            state,
            isInitialized,
        }),
        [state, isInitialized]
    );

    if (initError) {
        console.error('[VoiceProvider] voice unavailable:', initError.message);
    }

    return <VoiceContext.Provider value={value}>{children}</VoiceContext.Provider>;
}

/**
 * Use voice context
 */
function useVoiceContext(): VoiceContextValue {
    const context = useContext(VoiceContext);
    if (!context) {
        throw new Error('useVoice must be used within a VoiceProvider');
    }
    return context;
}

// ============================================================================
// MAIN HOOK — identical return shape to the old useVoice
// ============================================================================

export interface UseVoiceReturn {
    // State
    isInitialized: boolean;
    connectionState: VoiceConnectionState;
    isConnecting: boolean;
    isConnected: boolean;
    isMuted: boolean;
    isSpeaking: boolean;
    localAudioLevel: number;
    currentRoomId: string | null;
    remoteParticipants: RemoteParticipant[];
    error: Error | null;

    // Video / screen / publishing (Phase 3)
    isVideoOn: boolean;
    isSharingScreen: boolean;
    isPublishing: boolean;
    localVideoTrack: MediaStreamTrack | null;
    localScreenTrack: MediaStreamTrack | null;

    // Actions
    joinRoom: (roomId: string, opts?: JoinRoomOptions) => Promise<{ participants?: string[] }>;
    leaveRoom: () => Promise<void>;
    toggleMute: () => Promise<void>;
    setMuted: (muted: boolean) => Promise<void>;
    setVideoEnabled: (on: boolean) => Promise<void>;
    startScreenShare: () => Promise<void>;
    stopScreenShare: () => Promise<void>;
    setPublishing: (publish: boolean) => Promise<void>;

    // Audio devices
    audioDevices: AudioDeviceOptions[];
    selectedDeviceId: string | null;
    refreshDevices: () => Promise<void>;
    switchDevice: (deviceId: string) => Promise<void>;
}

/**
 * Main voice hook - provides all voice functionality
 */
export function useVoice(): UseVoiceReturn {
    const { service, state, isInitialized } = useVoiceContext();
    const [audioDevices, setAudioDevices] = useState<AudioDeviceOptions[]>([]);

    // Fetch audio devices on mount
    useEffect(() => {
        if (isInitialized) {
            service.getAudioDevices().then(setAudioDevices).catch(() => {});
        }
    }, [isInitialized, service]);

    // Convert remote participants map to array
    const remoteParticipants = useMemo(
        () => Array.from(state.remoteParticipants.values()),
        [state.remoteParticipants]
    );

    // Actions
    const joinRoom = useCallback(
        async (roomId: string, opts?: JoinRoomOptions) => {
            return await service.joinRoom(roomId, opts);
        },
        [service]
    );

    const leaveRoom = useCallback(async () => {
        await service.leaveRoom();
    }, [service]);

    const toggleMute = useCallback(async () => {
        await service.toggleMute();
    }, [service]);

    const setMuted = useCallback(
        async (muted: boolean) => {
            await service.setMuted(muted);
        },
        [service]
    );

    const setVideoEnabled = useCallback(
        async (on: boolean) => {
            await service.setVideoEnabled(on);
        },
        [service]
    );

    const startScreenShare = useCallback(async () => {
        await service.startScreenShare();
    }, [service]);

    const stopScreenShare = useCallback(async () => {
        await service.stopScreenShare();
    }, [service]);

    const setPublishing = useCallback(
        async (publish: boolean) => {
            await service.setPublishing(publish);
        },
        [service]
    );

    const refreshDevices = useCallback(async () => {
        const devices = await service.getAudioDevices();
        setAudioDevices(devices);
    }, [service]);

    const switchDevice = useCallback(
        async (deviceId: string) => {
            await service.switchAudioDevice(deviceId);
        },
        [service]
    );

    return {
        // State
        isInitialized,
        connectionState: state.connectionState,
        isConnecting: state.isConnecting,
        isConnected: state.isConnected,
        isMuted: state.isMuted,
        isSpeaking: state.isSpeaking,
        localAudioLevel: state.localAudioLevel,
        currentRoomId: state.currentRoomId,
        remoteParticipants,
        error: state.error,

        // Video / screen / publishing
        isVideoOn: state.isVideoOn,
        isSharingScreen: state.isSharingScreen,
        isPublishing: state.isPublishing,
        localVideoTrack: state.localVideoTrack,
        localScreenTrack: state.localScreenTrack,

        // Actions
        joinRoom,
        leaveRoom,
        toggleMute,
        setMuted,
        setVideoEnabled,
        startScreenShare,
        stopScreenShare,
        setPublishing,

        // Audio devices
        audioDevices,
        selectedDeviceId: state.selectedAudioInputId,
        refreshDevices,
        switchDevice,
    };
}

